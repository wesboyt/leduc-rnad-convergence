"""make_results.py -- build RESULTS.md from results/claims/*.json (the output of reproduce.py).

    python make_results.py
"""
import glob
import json
import os
import platform
import sys
import time

ROOT = os.path.dirname(os.path.abspath(__file__))


def fmt(v):
    if isinstance(v, float):
        return "%.4g" % v
    if isinstance(v, list):
        return "[" + ", ".join(fmt(x) for x in v) + "]"
    return str(v)


def main():
    recs = []
    for p in glob.glob(os.path.join(ROOT, "results", "claims", "C*.json")):
        recs.append(json.load(open(p)))
    recs.sort(key=lambda r: int(r["claim"][1:]))
    import numpy
    lines = ["# Results of `reproduce.py`", "",
             "Generated by `make_results.py` on %s (Python %s, numpy %s, %s)." % (
                 time.strftime("%Y-%m-%d"), platform.python_version(), numpy.__version__, platform.platform()),
             "Claims, criteria and original evidence: `docs/CLAIMS.md`.", "",
             "| claim | verdict | seconds | numbers |", "|---|---|---|---|"]
    for r in recs:
        nums = "; ".join("%s = %s" % (k, fmt(v)) for k, v in r["numbers"].items())
        lines.append("| %s | **%s** | %s | %s |" % (r["claim"], r["verdict"], r["seconds"], nums))
    sys.path.insert(0, ROOT)
    from reproduce import PAPERS
    lines += ["", "## Statements and the papers they bear on", "",
              "CONFIRMED = the paper's prediction reproduces. BOUNDARY = the guarantee does not carry over once a named "
              "hypothesis is dropped (refutes an extrapolation, not the paper). Details: `docs/PAPERS.md`.", ""]
    for r in recs:
        lines.append("* **%s** %s" % (r["claim"], r["statement"]))
        for p, rel in PAPERS.get(r["claim"], []):
            lines.append("  * %s — %s" % (p, rel))
    open(os.path.join(ROOT, "RESULTS.md"), "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote RESULTS.md (%d claims)" % len(recs))
    sys.exit(0)


if __name__ == "__main__":
    main()
